import { expect, test } from '@playwright/test'
import path from 'node:path'

test('real guest → Python recommendations → feedback → history reload → WAV and microphone pipeline', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
  const sessionResponse = page.waitForResponse(r => r.url().endsWith('/api/sessions/guest') && r.request().method() === 'POST')
  await page.getByRole('button', { name: /Войти в свой ритм/ }).click()
  expect((await sessionResponse).status()).toBe(201)
  await page.getByRole('button', { name: /Пропустить/ }).click()
  const text = 'Я устал после университета, хочу расслабиться под атмосферу Человека-паука'
  await page.getByLabel('Что сейчас у тебя на душе?').fill(text)
  const checkinResponse = page.waitForResponse(r => r.url().endsWith('/api/checkins'))
  await page.locator('button.find-vibe').click()
  const response = await checkinResponse
  expect(response.status()).toBe(200)
  const result = await response.json()
  expect(result.moodEntry.analysisMode).toBe('demo')
  expect(result.moodEntry.analysis.themes).toContain('spider-man')
  await expect(page.locator('.recommendation-card')).toHaveCount(5)
  await expect(page.locator('.recommendation-card').last()).toHaveCSS('opacity', '1')
  const feedbackResponse = page.waitForResponse(r => r.url().endsWith('/api/feedback'))
  await page.getByRole('button', { name: /^Нравится:/ }).first().click()
  expect((await feedbackResponse).status()).toBe(200)
  await expect(page.getByRole('button', { name: /^Нравится:/ }).first()).toHaveAttribute('aria-pressed', 'true')
  await page.goto('/history')
  await expect(page.getByText(text, { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText(text, { exact: true })).toBeVisible()
  await page.goto('/physics')
  await page.getByRole('button', { name: /У настроения есть голос/ }).click()
  const uploadResponse = page.waitForResponse(r => r.url().endsWith('/api/audio/analyze'))
  await page.getByLabel('Загрузить PCM WAV', { exact: true }).setInputFiles(path.resolve('e2e/fixtures/synthetic_880hz.wav'))
  const uploaded = await uploadResponse
  expect(uploaded.status()).toBe(200)
  const uploadedFeatures = await uploaded.json()
  expect(uploadedFeatures.dominantFrequencyHz).toBe(880)
  await expect(page.locator('.audio-analysis')).toBeVisible()
  await expect(page.locator('.audio-analysis')).toContainText('880.0')
  await expect(page.locator('.audio-analysis')).toContainText(uploadedFeatures.rms.toFixed(4))
  await page.getByRole('button', { name: 'Начать запись', exact: true }).click()
  await expect(page.getByRole('button', { name: /Остановить/ })).toBeVisible()
  await page.waitForTimeout(2200)
  await page.getByRole('button', { name: /Остановить/ }).click()
  await expect(page.getByRole('button', { name: 'Исследовать звук', exact: true })).toBeVisible()
  const recordingResponse = page.waitForResponse(r => r.url().endsWith('/api/audio/analyze'))
  await page.getByRole('button', { name: 'Исследовать звук', exact: true }).click()
  const recorded = await recordingResponse
  expect(recorded.status()).toBe(200)
  const features = await recorded.json()
  expect(Math.abs(features.dominantFrequencyHz - 440)).toBeLessThan(2)
  expect(features.rms).toBeGreaterThan(0.1)
  await expect(page.locator('.audio-analysis')).toContainText(features.dominantFrequencyHz.toFixed(1))
  await expect(page.locator('.audio-analysis')).toContainText(features.spectralCentroidHz.toFixed(1))
  expect(errors).toEqual([])
})
